-- Schema e-commerce PostgreSQL (Supabase)

DROP TABLE IF EXISTS commande CASCADE;
DROP TABLE IF EXISTS panier_ligne CASCADE;
DROP TABLE IF EXISTS panier CASCADE;
DROP TABLE IF EXISTS variant CASCADE;
DROP TABLE IF EXISTS categorie CASCADE;
DROP TABLE IF EXISTS produit CASCADE;
DROP TABLE IF EXISTS prix CASCADE;
DROP TABLE IF EXISTS adresse CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS marque CASCADE;
DROP TABLE IF EXISTS devise CASCADE;
DROP TABLE IF EXISTS promotion CASCADE;

CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255),
  nom VARCHAR(255),
  prenom VARCHAR(255),
  tel VARCHAR(255),
  password VARCHAR(255),
  role VARCHAR(255)
);

CREATE TABLE adresse (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  type VARCHAR(50) NOT NULL,
  ligne VARCHAR(255),
  ville VARCHAR(255),
  code_postal VARCHAR(20),
  pays VARCHAR(100),
  CONSTRAINT fk_user_id_adresse
    FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE marque (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(255),
  nom_commercial VARCHAR(255)
);

CREATE TABLE devise (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  valeur VARCHAR(255)
);

CREATE TABLE promotion (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  valeur VARCHAR(255),
  date DATE,
  nb_utilisation INTEGER
);

CREATE TABLE prix (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  valeur DECIMAL(10, 2),
  date DATE,
  devise_id INTEGER,
  CONSTRAINT fk_devise_id_prix
    FOREIGN KEY (devise_id) REFERENCES devise (id)
);

CREATE TABLE produit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(255),
  description VARCHAR(255),
  reference VARCHAR(255),
  marque_id INTEGER,
  prix_id INTEGER,
  CONSTRAINT fk_marque_id_produit
    FOREIGN KEY (marque_id) REFERENCES marque (id),
  CONSTRAINT fk_prix_id_produit
    FOREIGN KEY (prix_id) REFERENCES prix (id)
);

CREATE TABLE variant (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  produit_id INTEGER,
  nom VARCHAR(255),
  taille VARCHAR(255),
  couleur VARCHAR(255),
  reference VARCHAR(255),
  CONSTRAINT fk_produit_id_variant
    FOREIGN KEY (produit_id) REFERENCES produit (id)
);

CREATE TABLE categorie (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(255),
  produit_id INTEGER,
  promotion_id INTEGER,
  CONSTRAINT fk_produit_id_categorie
    FOREIGN KEY (produit_id) REFERENCES produit (id),
  CONSTRAINT fk_promotion_id_categorie
    FOREIGN KEY (promotion_id) REFERENCES promotion (id)
);

-- Panier = panier d'un user (peut contenir plusieurs produits)
CREATE TABLE panier (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER,
  promotion_id INTEGER,
  CONSTRAINT fk_user_id_panier
    FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_promotion_id_panier
    FOREIGN KEY (promotion_id) REFERENCES promotion (id)
);

-- Une ligne = un produit + quantite dans le panier
CREATE TABLE panier_ligne (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  panier_id INTEGER NOT NULL,
  produit_id INTEGER NOT NULL,
  nb_produit INTEGER NOT NULL DEFAULT 1,
  CONSTRAINT fk_panier_id_ligne
    FOREIGN KEY (panier_id) REFERENCES panier (id),
  CONSTRAINT fk_produit_id_ligne
    FOREIGN KEY (produit_id) REFERENCES produit (id)
);

-- montant = total calcule a partir des lignes (prix x quantite)
CREATE TABLE commande (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nom VARCHAR(255),
  adresse_id INTEGER,
  user_id INTEGER,
  panier_id INTEGER,
  mail VARCHAR(255),
  montant DECIMAL(10, 2) NOT NULL DEFAULT 0,
  statut VARCHAR(50) NOT NULL DEFAULT 'en_cours',
  date_commande DATE NOT NULL DEFAULT CURRENT_DATE,
  CONSTRAINT fk_adresse_id_commande
    FOREIGN KEY (adresse_id) REFERENCES adresse (id),
  CONSTRAINT fk_user_id_commande
    FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_panier_id_commande
    FOREIGN KEY (panier_id) REFERENCES panier (id)
);
